def gen(n,en,ar,intro,sub,subar,fsay,flines,esay,erows,qsay,qrows,qpage,psay,wrong,right,endsay,endnote,endar):
    st=[dict(say=intro,write=[('title',en),('sub',sub,subar)]),
        dict(say=fsay,write=[('line',)+tuple(x) for x in flines]),
        dict(page=True,say=esay,write=[('ex',)+tuple(r) for r in erows])]
    if qsay:st.append(dict(page=qpage,say=qsay,write=[('ex',)+tuple(r) for r in qrows]))
    st.append(dict(page=(not qpage),say=psay,write=[('wrong',wrong,'خطأ'),('right',right,'صحيح')]))
    st.append(dict(say=endsay,write=[('note',endnote,endar)]))
    A(dict(n=n,en=en,ar=ar,steps=st))
